#!/usr/bin/env python3
"""Reduce the bug corpus with shrink ray against real buggy tools.

Each corpus entry (evaluation/corpus/<id>/) is an input file that makes a
specific pinned version of a real tool fail in a specific way: a compiler
crashing with an ICE, a formatter raising an internal error, a linter
crashing, a SAT solver hitting an assertion. This script runs shrink ray
on each one, using the real tool as the interestingness oracle, and
records how far each was reduced in <entry>/result.json.

Each entry's meta.json declares how to run its tool via an "oracle":

  docker    a pinned Docker image (old compilers). A persistent container
            is started once per entry and reused across the thousands of
            oracle calls a reduction makes. amd64-only images run under
            emulation on Apple Silicon: slow but works, and emulation
            penalises concurrency, so these entries set parallelism 1.
  venv      pinned Python packages, installed with uv into a per-entry
            virtualenv (formatters, linters, type checkers).
  command   an arbitrary command, optionally with a setup script that
            builds a pinned tool from source into evaluation/tools/.

Usage:
    python3 run.py                 # reduce every entry
    python3 run.py <entry-id> ...  # reduce specific entries
    python3 run.py --check         # just verify each entry still fails
"""

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path


EVAL_DIR = Path(__file__).parent
CORPUS_DIR = EVAL_DIR / "corpus"
TOOLS_DIR = EVAL_DIR / "tools"
REPO_ROOT = EVAL_DIR.parent


def load_entries(names: list[str]) -> list[dict]:
    entries = []
    for meta_path in sorted(CORPUS_DIR.glob("*/meta.json")):
        meta = json.loads(meta_path.read_text())
        meta["dir"] = meta_path.parent
        if not names or meta["id"] in names:
            entries.append(meta)
    return entries


def substitute(arg: str, placeholders: dict[str, str]) -> str:
    """Render one command argument into a bash word.

    Literal text is shlex-quoted; placeholder occurrences are replaced by
    their (already bash-safe) expansions, e.g. '"$tmp"'.
    """
    pattern = "|".join(re.escape(k) for k in placeholders)
    pieces = re.split(f"({pattern})", arg)
    out = []
    for piece in pieces:
        if piece in placeholders:
            out.append(placeholders[piece])
        elif piece:
            out.append(shlex.quote(piece))
    return "".join(out) or "''"


class Oracle:
    """Runs a corpus entry's buggy tool. Subclasses provide setup/teardown
    and the command line that the generated check script executes."""

    def __init__(self, entry: dict, workdir: Path):
        self.entry = entry
        self.workdir = workdir
        self.config = entry["oracle"]

    def setup(self) -> None:
        pass

    def teardown(self) -> None:
        pass

    def placeholders(self) -> dict[str, str]:
        """Bash expansions for placeholders usable in oracle commands."""
        return {
            "{file}": '"$candidate"',
            "{sandbox}": '"$PWD"',
            "{tools}": shlex.quote(str(TOOLS_DIR)),
            "{entry}": shlex.quote(str(self.entry["dir"])),
            "{workdir}": shlex.quote(str(self.workdir)),
        }

    def command_line(self) -> str:
        parts = [substitute(arg, self.placeholders()) for arg in self.config["command"]]
        return " ".join(parts)

    def path_prefix(self) -> str | None:
        """Directory to prepend to PATH in the check script, if any."""
        return None

    def check_script(self) -> str:
        # Native oracles read the candidate as a file. shrink ray runs this
        # test in a fresh temp dir it creates and deletes for each candidate,
        # having written the candidate there (with its real extension) as our
        # $1. Point the tool's own temp files at that same directory so
        # everything the test produces is cleaned up with it, rather than
        # piling up next to the corpus entry.
        return self._finish_check_script(
            [
                "#!/bin/bash",
                f"# Generated by evaluation/run.py for {self.entry['id']}.",
                "# Do not edit; edit meta.json instead.",
                "set -u",
                'candidate="$1"',
                'export TMPDIR="$PWD"',
            ]
        )

    def _finish_check_script(self, lines: list[str]) -> str:
        entry = self.entry
        prefix = self.path_prefix()
        if prefix is not None:
            lines.append(f"export PATH={shlex.quote(prefix)}:$PATH")
        for key, value in self.config.get("env", {}).items():
            lines.append(f"export {key}={substitute(value, self.placeholders())}")
        lines.append(f"out=$({self.command_line()} 2>&1)")
        lines.append("status=$?")
        interesting = entry["interesting"]
        contains = interesting.get("output_contains", [])
        if isinstance(contains, str):
            contains = [contains]
        for needle in contains:
            lines.append(
                f"printf '%s' \"$out\" | grep -Fq -- {shlex.quote(needle)} || exit 1"
            )
        if "exit_code" in interesting:
            lines.append(f'[ "$status" -eq {interesting["exit_code"]} ] || exit 1')
        lines.append("exit 0")
        return "\n".join(lines) + "\n"


class DockerOracle(Oracle):
    @property
    def container(self) -> str:
        return "srbug-" + self.entry["id"]

    def setup(self) -> None:
        # No volumes are mounted: the candidate reaches the compiler on the
        # container's stdin (shrink ray runs docker entries in stdin mode),
        # so nothing needs to be shared into the container.
        subprocess.run(["docker", "rm", "-f", self.container], capture_output=True)
        subprocess.run(
            [
                "docker", "run", "-d",
                "--platform", self.config.get("platform", "linux/amd64"),
                "--name", self.container,
                self.config["image"], "sleep", "infinity",
            ],
            check=True, capture_output=True,
        )

    def teardown(self) -> None:
        subprocess.run(["docker", "rm", "-f", self.container], capture_output=True)

    def check_script(self) -> str:
        # The candidate arrives on our stdin; pipe it straight into the
        # compiler in the container via `docker exec -i`, which forwards
        # stdin, so the compiler reads it as `-` (stdin) and no file has to
        # be shared into the container.
        return self._finish_check_script(
            [
                "#!/bin/bash",
                f"# Generated by evaluation/run.py for {self.entry['id']}.",
                "# Do not edit; edit meta.json instead.",
                "set -u",
            ]
        )

    def placeholders(self) -> dict[str, str]:
        # The compiler reads the candidate from stdin, so {file} is `-`.
        return super().placeholders() | {"{file}": "-"}

    def command_line(self) -> str:
        return (
            f"docker exec -i {shlex.quote(self.container)} " + super().command_line()
        )


class VenvOracle(Oracle):
    @property
    def venv(self) -> Path:
        return self.workdir / "venv"

    def setup(self) -> None:
        stamp = self.workdir / "venv.stamp"
        spec = json.dumps(
            {
                "python": self.config["python"],
                "requirements": self.config["requirements"],
            },
            sort_keys=True,
        )
        if stamp.exists() and stamp.read_text() == spec and self.venv.exists():
            return
        shutil.rmtree(self.venv, ignore_errors=True)
        subprocess.run(
            ["uv", "venv", "--python", self.config["python"], str(self.venv)],
            check=True, capture_output=True,
        )
        if self.config["requirements"]:
            subprocess.run(
                [
                    "uv", "pip", "install",
                    "--python", str(self.venv / "bin" / "python"),
                    *self.config["requirements"],
                ],
                check=True, capture_output=True,
            )
        stamp.write_text(spec)

    def path_prefix(self) -> str:
        return str(self.venv / "bin")


class CommandOracle(Oracle):
    def setup(self) -> None:
        setup = self.config.get("setup")
        if setup is None:
            return
        TOOLS_DIR.mkdir(exist_ok=True)
        env = dict(os.environ, TOOLS_DIR=str(TOOLS_DIR))
        subprocess.run(
            ["bash", setup], cwd=self.entry["dir"], env=env, check=True,
        )


ORACLE_TYPES = {
    "docker": DockerOracle,
    "venv": VenvOracle,
    "command": CommandOracle,
}


def make_oracle(entry: dict, workdir: Path) -> Oracle:
    return ORACLE_TYPES[entry["oracle"]["type"]](entry, workdir)


def prepare(entry: dict) -> tuple[Oracle, Path]:
    """Create the entry's work dir and oracle, and write its check script."""
    workdir = entry["dir"] / "work"
    workdir.mkdir(exist_ok=True)
    oracle = make_oracle(entry, workdir)
    oracle.setup()
    check = workdir / "check.sh"
    check.write_text(oracle.check_script())
    check.chmod(0o755)
    return oracle, check


def is_interesting(check: Path, source: Path) -> bool:
    # Pass the candidate both as an argument (native oracles read the file)
    # and on stdin (docker oracles pipe it into the container), and run in a
    # throwaway temp dir so anything a tool writes beside its cwd is cleaned
    # up — mirroring how shrink ray sandboxes each test during reduction.
    with tempfile.TemporaryDirectory() as scratch, open(source, "rb") as stdin:
        return (
            subprocess.run(
                ["bash", str(check), str(source)], stdin=stdin, cwd=scratch
            ).returncode
            == 0
        )


def original_path(entry: dict) -> Path:
    return entry["dir"] / ("original" + entry["extension"])


def nows_size(path: Path) -> int:
    return len(re.sub(rb"\s+", b"", path.read_bytes()))


def reduce_entry(entry: dict, parallelism: int | None = None) -> dict:
    """Reduce a single entry and return a result record.

    parallelism, if given, overrides the entry's own parallelism setting
    (and shrink ray's all-cores default) — useful for bounding the load a
    reduction places on the machine.
    """
    oracle, check = prepare(entry)
    workdir = entry["dir"] / "work"
    source = workdir / ("reduced" + entry["extension"])
    # shrink ray writes the current best back to `source` as it goes (in
    # both in-place and normal mode), so resume from an in-progress
    # reduction if one is present, letting an interrupted run restart
    # without losing work.
    if not source.exists():
        shutil.copy(original_path(entry), source)

    try:
        if not is_interesting(check, source):
            return {
                "id": entry["id"],
                "status": "ERROR: original does not reproduce the failure",
            }

        start = time.time()
        # An explicit timeout avoids shrink ray's dynamic-timeout
        # calibration, which would otherwise probe with a slow first call.
        command = [
            "uv", "run", "shrinkray",
            "--ui=basic", "--no-history", "--no-restart",
            f"--timeout={entry.get('timeout', 10)}",
        ]
        # Every entry runs in shrink ray's normal mode, where each test
        # executes in a temp dir that shrink ray creates and removes,
        # cleaning up anything the tool writes beside the candidate. Docker
        # oracles additionally feed the candidate to the container on stdin
        # (the compiler reads `-`), so nothing has to be shared into the
        # container and there is no in-place reduction in the corpus tree.
        if entry["oracle"]["type"] == "docker":
            command.append("--input-type=stdin")
        effective_parallelism = (
            parallelism if parallelism is not None else entry.get("parallelism")
        )
        if effective_parallelism is not None:
            command.append(f"--parallelism={effective_parallelism}")
        command += entry.get("shrinkray_args", [])
        command += [str(check), str(source)]
        # Stream shrink ray's progress to a per-entry log rather than
        # capturing it in memory, so a long reduction can be watched live
        # (e.g. `tail -f <entry>/work/reduce.log`) instead of going dark
        # until it finishes.
        log_path = workdir / "reduce.log"
        with open(log_path, "w") as log:
            proc = subprocess.run(
                command, cwd=REPO_ROOT, stdout=log, stderr=subprocess.STDOUT,
            )
        elapsed = time.time() - start

        if proc.returncode != 0:
            return {
                "id": entry["id"],
                "status": f"ERROR: shrinkray exited {proc.returncode}",
                "stderr": log_path.read_text()[-2000:],
            }

        if not is_interesting(check, source):
            return {
                "id": entry["id"],
                "status": "ERROR: reduced file no longer reproduces the failure",
            }

        reduced_copy = entry["dir"] / ("shrinkray_reduced" + entry["extension"])
        shutil.copy(source, reduced_copy)
        original = original_path(entry)
        result = {
            "id": entry["id"],
            "status": "ok",
            "original_bytes": original.stat().st_size,
            "reduced_bytes": reduced_copy.stat().st_size,
            "original_nows_bytes": nows_size(original),
            "reduced_nows_bytes": nows_size(reduced_copy),
            "seconds": round(elapsed, 1),
        }
        result["ratio"] = round(
            100 * (1 - result["reduced_bytes"] / result["original_bytes"]), 1
        )
        (entry["dir"] / "result.json").write_text(json.dumps(result, indent=2) + "\n")
        return result
    finally:
        oracle.teardown()


def check_entry(entry: dict) -> dict:
    oracle, check = prepare(entry)
    try:
        ok = is_interesting(check, original_path(entry))
        return {"id": entry["id"], "reproduces": ok}
    finally:
        oracle.teardown()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ids", nargs="*", help="entry ids to run (default: all)")
    parser.add_argument(
        "--check", action="store_true",
        help="only verify each entry still reproduces its failure",
    )
    parser.add_argument(
        "--parallelism", type=int, default=None,
        help="override each reduction's parallelism (bounds machine load)",
    )
    args = parser.parse_args()

    entries = load_entries(args.ids)
    if not entries:
        print("no matching corpus entries", file=sys.stderr)
        return 2

    if any(e["oracle"]["type"] == "docker" for e in entries):
        if shutil.which("docker") is None:
            print("docker not found on PATH", file=sys.stderr)
            return 2

    results = []
    for entry in entries:
        action = "Checking" if args.check else "Reducing"
        print(f"{action} {entry['id']} ({entry['tool']}) ...", flush=True)
        record = (
            check_entry(entry)
            if args.check
            else reduce_entry(entry, parallelism=args.parallelism)
        )
        results.append(record)
        print("   " + json.dumps(record), flush=True)

    print("\n=== summary ===")
    print(json.dumps(results, indent=2))
    ok = all(
        r.get("reproduces") if args.check else r.get("status") == "ok"
        for r in results
    )
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
