"""Render the inversion findings into a readable markdown report.

Reads ``corpus/_inversions/<lang>.json`` (produced by inversions.py) and writes
``corpus/_inversions/REPORT.md``: the chosen formatter per language, the
sort-key/formatter disagreement rates, which sort-key criterion is most often
responsible for a flip, and a few concrete example pairs.

    python evaluation/sortkey/report.py
"""

from __future__ import annotations

import base64
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from gather import corpus_dir  # noqa: E402
from langs import LANGUAGES  # noqa: E402

FENCE = {
    "c": "c",
    "cpp": "cpp",
    "python": "python",
    "sql": "sql",
    "json": "json",
    "xml": "xml",
    "html": "html",
}


def merge_tally(seeds: dict) -> dict[str, int]:
    total: dict[str, int] = {}
    for seed in seeds.values():
        for crit, n in seed["flip_criterion_tally"]["fmt"].items():
            total[crit] = total.get(crit, 0) + n
    return dict(sorted(total.items(), key=lambda kv: kv[1], reverse=True))


def render_example(ex: dict, fence: str) -> list[str]:
    def block(label: str, b64: str) -> list[str]:
        text = base64.b64decode(b64).decode("utf-8", "replace").rstrip("\n")
        return [f"*{label}*", f"```{fence}", text, "```", ""]

    lines = [
        f"- Sort key prefers **x** over **y** (flips on `{ex['criterion_raw']}`), "
        f"but formatted **x** is *larger* than formatted **y** "
        f"(flips on `{ex['criterion_fmt']}`):",
        "",
    ]
    lines += block("x (raw, sort-key-smaller)", ex["x"])
    lines += block("y (raw, sort-key-larger)", ex["y"])
    lines += block("format(x)", ex["fx"])
    lines += block("format(y)", ex["fy"])
    return lines


def main() -> int:
    inv_dir = corpus_dir() / "_inversions"
    files = sorted(inv_dir.glob("*.json"))
    if not files:
        print("no inversion data; run inversions.py first")
        return 1
    out: list[str] = [
        "# Sort-key vs. formatter disagreements",
        "",
        "Generated by `evaluation/sortkey/report.py`. Each row counts pairs of "
        "gathered valid programs where shrink ray's current sort key prefers one "
        "form but the formatter, applied to both, prefers the other "
        "(`sort_key(x) < sort_key(y)` yet `sort_key(format(x)) > sort_key(format(y))`).",
        "",
        "These are **starting points for investigation, not proven sort-key "
        "defects**: a formatter is only one proxy for human preference, and in "
        "many pairs the sort key may be perfectly reasonable. A disagreement is "
        "simply a place worth looking at.",
        "",
        "The **rate** is over all comparable pairs. The **flip-criterion** tally "
        "and the example pairs are drawn from *adjacent-in-sort-key* inversions "
        "with degenerate (near-empty) candidates filtered out, so they reflect "
        "meaningful, tightly-adjacent disagreements.",
        "",
        "## Formatter chosen per language",
        "",
        "| Language | Parser (validity gate) | Formatter |",
        "| --- | --- | --- |",
    ]
    parsers = {
        "c": "clang -fsyntax-only (C11)",
        "cpp": "clang -fsyntax-only (C++17)",
        "python": "ast.parse",
        "sql": "sqlglot (multi-dialect)",
        "json": "json.loads",
        "xml": "lxml (strict)",
        "html": "html5lib (strict)",
    }
    for name, lang in LANGUAGES.items():
        out.append(f"| {name} | {parsers[name]} | {lang.formatter} |")
    out += ["", "## Disagreement rates", ""]

    data = {f.stem: json.loads(f.read_text()) for f in files}
    for name in LANGUAGES:
        if name not in data:
            continue
        d = data[name]
        out += [
            f"### {name}  (formatter: {d['formatter']})",
            "",
            "| Seed | Candidates | Inversions / pairs | Rate | Flip criterion (formatted) |",
            "| --- | ---: | ---: | ---: | --- |",
        ]
        for seed, s in d["seeds"].items():
            tally = ", ".join(
                f"{k}:{v}" for k, v in s["flip_criterion_tally"]["fmt"].items()
            )
            out.append(
                f"| {seed} | {s['candidates']} | "
                f"{s['inversions']} / {s['comparable_pairs']} | "
                f"{s['inversion_rate_pct']:.1f}% | {tally} |"
            )
        agg = merge_tally(d["seeds"])
        agg_str = ", ".join(f"`{k}` {v}" for k, v in agg.items())
        out += ["", f"Aggregate flip criterion: {agg_str}", ""]

        # One illustrative example: the median-size inversion pair across all
        # seeds. The smallest pairs tend to be over-minimal fragments and the
        # largest are whole programs; the median is the most readable/realistic.
        candidates = sorted(
            (
                (seed, ex)
                for seed, s in d["seeds"].items()
                for ex in s["examples"]
            ),
            key=lambda se: len(base64.b64decode(se[1]["fx"]))
            + len(base64.b64decode(se[1]["fy"])),
        )
        if candidates:
            seed, ex = candidates[len(candidates) // 2]
            out += [f"Example (from `{seed}`):", ""]
            out += render_example(ex, FENCE[name])

    report = corpus_dir() / "_inversions" / "REPORT.md"
    report.write_text("\n".join(out))
    print(f"wrote {report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
